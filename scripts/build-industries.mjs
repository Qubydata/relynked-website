function shell() {
  const p = readFileSync(join(ROOT, 'pricing.html'), 'utf8');
  const grab = (re, what) => { const m = p.match(re); if (!m) throw new Error(`Could not find the ${what} in pricing.html`); return m[0]; };
  const headLinks = grab(/<link rel="icon"[\s\S]*?<link rel="stylesheet"[^>]*>/, 'head links');
  const nav = grab(/<nav class="nav[\s\S]*?<\/nav>/, 'nav');
  const tail = grab(/<footer>[\s\S]*?<\/body>/, 'footer');
  return { headLinks, nav, tail };
}


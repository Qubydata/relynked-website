// Builds the "Who Relynked is for" pages from the product's own list of business types,
// so the list on the website can never drift from what the app supports.
//
//   node scripts/build-industries.mjs
//
// Reads   https://relynked-api-production.up.railway.app/business-types  (no auth)
//         falling back to scripts/industries-fallback.json when the API is unreachable
//         or does not yet return categories and aliases.
// Writes  industries/<slug>.html (one per type), the full list inside
//         product.html (between the WHO-ITS-FOR markers), sitemap.xml and
//         robots.txt. The list lives on Products (founder, 2026-09-24): the
//         home page carries a short summary and links there.
// Takes   the head, nav and footer from pricing.html, so a footer change there
//         reaches these pages on the next run.
//
// Node 18 or newer. No dependencies.


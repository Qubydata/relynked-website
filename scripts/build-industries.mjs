function injectProductSection(cats) {
  const file = join(ROOT, 'product.html');
  let html = readFileSync(file, 'utf8');
  const block = productSection(cats);
  if (html.includes('<!-- WHO-ITS-FOR:START -->')) {
    html = html.replace(/<!-- WHO-ITS-FOR:START -->[\s\S]*?<!-- WHO-ITS-FOR:END -->/, block);
  } else {
    // First run: straight after the products grid.
    const at = html.indexOf('</section>', html.indexOf('id="surfaces"')) + '</section>'.length;
    html = `${html.slice(0, at)}\n\n${block}${html.slice(at)}`;
  }
  return writeIfChanged(file, html);
}


// ---------------------------------------------------------------- sitemap and robots

function sitemap(cats) {
  const iso = d => d.toISOString().slice(0, 10);
  const entries = [];
  for (const f of readdirSync(ROOT).filter(f => f.endsWith('.html')).sort()) {
    if (f === 'dashboard.html') continue;
    const html = readFileSync(join(ROOT, f), 'utf8');
    if (/<meta name="robots" content="[^"]*noindex/i.test(html)) continue;
    const loc = f === 'index.html' ? `${SITE}/` : `${SITE}/${f.replace(/\.html$/, '')}`;
    entries.push([loc, iso(statSync(join(ROOT, f)).mtime)]);
  }
  for (const t of cats.flatMap(c => c.types)) entries.push([t.url, iso(statSync(join(OUT_DIR, `${t.slug}.html`)).mtime)]);
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-industries.mjs. Re-run it after adding a page. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries.map(([loc, lastmod]) => `  <url><loc>${loc}</loc><lastmod>${lastmod}</lastmod></url>`).join('\n')}
</urlset>
`;
}

const ROBOTS = `# Generated by scripts/build-industries.mjs
User-agent: *
Allow: /
Disallow: /dashboard
Disallow: /api/

Sitemap: ${SITE}/sitemap.xml
`;

// ---------------------------------------------------------------- write

function writeIfChanged(file, content) {
  if (/[\u2013\u2014]/.test(content)) throw new Error(`${file} contains an em dash or en dash. House style forbids them.`);
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return false;
  writeFileSync(file, content);
  return true;
}


async function fetchApi() {
  try {
    const res = await fetch(API, { signal: AbortSignal.timeout(20000), headers: { accept: 'application/json' } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const json = await res.json();
    if (!Array.isArray(json.types) || !json.types.length) throw new Error('no types in response');
    return json;
  } catch (e) {
    console.warn(`! Could not read ${API}: ${e.message}`);
    return null;
  }
}

function loadData(api) {
  const fb = JSON.parse(readFileSync(join(ROOT, 'scripts', 'industries-fallback.json'), 'utf8'));
  const apiComplete = api && Array.isArray(api.categories) && api.categories.length
    && api.types.every(t => 'category_key' in t && Array.isArray(t.aliases));
  let types, categories, source;
  if (apiComplete) {
    source = 'live API';
    types = api.types;
    categories = api.categories;
  } else if (api) {
    // The API lists the types but not yet their categories and aliases.
    // The API decides which types exist; the fallback fills in the rest.
    source = 'live API, with categories, aliases and labels from the fallback';
    const byKey = Object.fromEntries(fb.types.map(t => [t.key, t]));
    types = api.types.map(t => {
      const f = byKey[t.key] || {};
      return {
        ...t,
        label: f.label || t.label,
        category_key: t.category_key ?? f.category_key ?? null,
        aliases: t.aliases?.length ? t.aliases : (f.aliases || []),
        groups: t.groups?.length ? t.groups : (f.groups || []),
        vocabulary: t.vocabulary || f.vocabulary,
      };
    });
    categories = fb.categories;
  } else {
    source = 'fallback file only';
    types = fb.types;
    categories = fb.categories;
  }

  const cats = categories
    .filter(c => !SKIP_CATEGORIES.has(c.key))
    .map(c => ({ ...c, aliases: c.aliases || [], types: [] }))
    .sort((a, b) => (a.sort ?? 0) - (b.sort ?? 0));
  const catByKey = Object.fromEntries(cats.map(c => [c.key, c]));
  let more = null;

  for (const raw of [...types].sort((a, b) => (a.sort ?? 0) - (b.sort ?? 0) || a.label.localeCompare(b.label))) {
    if (SKIP_TYPES.has(raw.key) || SKIP_CATEGORIES.has(raw.category_key)) continue;
    const t = decorate(raw);
    let cat = catByKey[raw.category_key];
    if (!cat) {
      console.warn(`! Type "${raw.key}" has no known category; listing it under "More businesses".`);
      more ||= { key: '_more', label: 'More businesses', aliases: [], sort: 9998, types: [] };
      cat = more;
    }
    t.category = cat;
    cat.types.push(t);
  }
  if (more) cats.push(more);
  const out = cats.filter(c => c.types.length);

  const slugs = new Set();
  for (const t of out.flatMap(c => c.types)) {
    if (slugs.has(t.slug)) throw new Error(`Two types share the slug "${t.slug}". Add a slug hint in HINTS.`);
    slugs.add(t.slug);
  }
  return { source, categories: out };
}


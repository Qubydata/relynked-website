const lc = s => s.toLowerCase();
function pluralWord(w) {
  if (/[^aeiou]y$/i.test(w)) return w.slice(0, -1) + 'ies';
  if (/(s|sh|ch|x|z)$/i.test(w)) return /s$/i.test(w) && !/ss$/i.test(w) ? w : w + 'es';
  return w + 's';
}
function pluralPhrase(p) {
  const words = p.trim().split(/\s+/);
  words[words.length - 1] = pluralWord(words[words.length - 1]);
  return words.join(' ');
}
const lastWord = s => lc(s.trim().split(/\s+/).pop());

function names(t) {
  const h = HINTS[t.key] || {};
  const label = lc(t.label);
  const parts = label.split(/\s+or\s+/);
  const countable = COUNTABLE.has(lastWord(label));
  const singular = h.singular || (countable ? label : `${label} business`);
  const plural = h.plural || (countable ? parts.map(pluralPhrase).join(' and ') : `${label} businesses`);
  const slug = h.slug || t.slug || slugify(t.label.split(/\s+or\s+/i)[0]);
  return { singular, plural, slug };
}

function slugify(s) {
  return lc(s).normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

function family(t) {
  const m = t.modules || [];
  if (m.includes('menu')) return 'food';
  if (t.vocabulary?.item === 'service' || m.includes('bookings')) return 'service';
  if (m.includes('quantity')) return 'shop';
  return 'general';
}

function decorate(raw) {
  const t = { ...raw, aliases: [...new Set((raw.aliases || []).map(a => a.trim()).filter(Boolean))], groups: raw.groups || [] };
  Object.assign(t, names(t));
  t.family = family(t);
  t.catalogue = t.vocabulary?.catalogue || (t.family === 'food' ? 'menu' : t.family === 'service' ? 'services' : 'products');
  t.url = `${SITE}/industries/${t.slug}`;
  t.path = `/industries/${t.slug}`;
  return t;
}

// "a, b or c"
function orList(xs, joiner = 'or') {
  if (xs.length <= 1) return xs.join('');
  return `${xs.slice(0, -1).join(', ')} ${joiner} ${xs[xs.length - 1]}`;
}
const cap = s => s.charAt(0).toUpperCase() + s.slice(1);
const aliasPlurals = t => t.aliases.map(a => pluralPhrase(lc(a)));

// "Barber shops, also called barbing salons or barbershops"
function alsoCalled(t, max = 3) {
  const al = aliasPlurals(t).slice(0, max);
  return al.length ? `${cap(t.plural)}, also called ${orList(al)}` : cap(t.plural);
}

